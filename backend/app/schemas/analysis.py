from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any

class AccuracyMetrics(BaseModel):
    mae: float = Field(..., description="Mean Absolute Error in MW")
    rmse: float = Field(..., description="Root Mean Squared Error in MW")
    meanBias: float = Field(..., description="Mean Error (Forecast - Actual) in MW. Positive = Overforecast, Negative = Underforecast")
    mape: Optional[float] = Field(None, description="Mean Absolute Percentage Error (%), calculated only for non-zero/non-near-zero actuals")
    validMapeObservations: int = Field(..., description="Number of observations included in MAPE calculation")
    excludedZeroActualCount: int = Field(..., description="Number of zero or near-zero observations excluded from MAPE to avoid infinite error")
    totalMatchedIntervals: int = Field(..., description="Total intervals with both valid forecast and actual")
    missingForecastIntervals: int = Field(..., description="Intervals in target window with missing forecast")
    missingActualIntervals: int = Field(..., description="Intervals in target window with missing actual outturn")
    overforecastCount: int = Field(..., description="Count of intervals where forecast exceeded actual")
    overforecastPercentage: float = Field(..., description="Percentage of intervals overforecasted")
    underforecastCount: int = Field(..., description="Count of intervals where actual exceeded forecast")
    underforecastPercentage: float = Field(..., description="Percentage of intervals underforecasted")
    interpretation: str = Field(..., description="Automated qualitative business interpretation of error characteristics")

class DailyAccuracy(BaseModel):
    date: str = Field(..., description="Delivery date YYYY-MM-DD")
    mae: float = Field(..., description="Mean Absolute Error in MW")
    rmse: float = Field(..., description="Root Mean Squared Error in MW")
    meanBias: float = Field(..., description="Mean Error (Forecast - Actual) in MW")
    forecastEnergyMwh: float = Field(..., description="Total forecast energy in MWh")
    actualEnergyMwh: float = Field(..., description="Total actual energy delivered in MWh")
    energyVarianceMwh: float = Field(..., description="Energy variance (Forecast MWh - Actual MWh)")
    maxOverforecastMw: float = Field(..., description="Maximum overforecast error in MW")
    maxUnderforecastMw: float = Field(..., description="Maximum underforecast error in MW")
    matchedIntervals: int = Field(..., description="Number of matched intervals on this day")

class HourlyBiasProfile(BaseModel):
    hour: int = Field(..., description="Hour of the day 0-23 in UK local time")
    meanBias: float = Field(..., description="Average error (Forecast - Actual) for this hour in MW")
    meanForecast: float = Field(..., description="Average forecast in MW")
    meanActual: float = Field(..., description="Average actual in MW")
    mae: float = Field(..., description="Mean Absolute Error for this hour in MW")
    observationCount: int = Field(..., description="Number of observations")

class ErrorDistributionBucket(BaseModel):
    rangeLabel: str = Field(..., description="Bucket label (e.g., '< -2000 MW', '-1000 to 0 MW')")
    minVal: float = Field(..., description="Minimum error value in MW")
    maxVal: float = Field(..., description="Maximum error value in MW")
    count: int = Field(..., description="Number of intervals in bucket")
    percentage: float = Field(..., description="Percentage of total matched intervals")

class MatchedTimeseriesPoint(BaseModel):
    startTime: str = Field(..., description="Delivery interval start time (ISO 8601 UTC)")
    startTimeLocal: str = Field(..., description="Delivery interval start time in UK local time")
    deliveryDate: str = Field(..., description="Delivery date YYYY-MM-DD in UK local time")
    deliveryHour: int = Field(..., description="Hour of delivery 0-23 in UK local time")
    generationForecast: float = Field(..., description="Selected forecast wind generation in MW")
    generationActual: float = Field(..., description="Actual wind generation outturn in MW")
    forecastError: float = Field(..., description="Forecast Error = Forecast - Actual in MW")
    absoluteError: float = Field(..., description="Absolute Error = |Forecast - Actual| in MW")
    publishTime: str = Field(..., description="Publication time of selected forecast snapshot (UTC)")
    publishTimeLocal: str = Field(..., description="Publication time of selected forecast snapshot in UK local time")
    decisionCutoffLocal: str = Field(..., description="Decision cutoff applied for this delivery day")
    shortfallMw: float = Field(..., description="Wind generation shortfall = max(0, Forecast - Actual) in MW")
    status: str = Field("MATCHED", description="'MATCHED', 'MISSING_ACTUAL', or 'MISSING_FORECAST'")

class ProcurementInsightPoint(BaseModel):
    startTime: str = Field(..., description="Delivery interval start time (ISO UTC)")
    startTimeLocal: str = Field(..., description="Delivery interval start time in UK local time")
    generationForecast: float = Field(..., description="Day-ahead forecast generation in MW")
    generationActual: Optional[float] = Field(None, description="Actual generation in MW (if available)")
    shortfallMw: float = Field(..., description="Shortfall vs forecast: max(0, Forecast - Actual) in MW")
    isShortfall: bool = Field(..., description="True if actual generation was below forecast")
    downsideScenarioMw: float = Field(..., description="Conservative P10 downside wind estimate in MW")
    publishTimeLocal: str = Field(..., description="Forecast publication time in UK local time")
    decisionCutoffLocal: str = Field(..., description="Decision cutoff applied in UK local time")

class ProcurementAnalysisResponse(BaseModel):
    totalShortfallEnergyMwh: float = Field(..., description="Total uncontracted wind shortfall energy in MWh")
    maxShortfallMw: float = Field(..., description="Peak single-interval shortfall in MW")
    meanShortfallWhenDeficitMw: float = Field(..., description="Average shortfall across deficit intervals in MW")
    shortfallIntervalsCount: int = Field(..., description="Number of intervals where actual wind fell short of forecast")
    shortfallPercentage: float = Field(..., description="Percentage of intervals experiencing a shortfall")
    downsideMethodology: str = Field(..., description="Explanation of how the downside scenario is calculated")
    operationalDisclaimer: str = Field(..., description="Mandatory operational disclaimer clarifying that wind shortfall is not net utility deficit")
    points: List[ProcurementInsightPoint] = Field(..., description="Detailed interval-level procurement points")

class ExecutiveSummaryKpis(BaseModel):
    latestEligibleForecastMw: Optional[float] = Field(None, description="Most recent eligible wind forecast in MW")
    selectedDecisionCutoff: str = Field(..., description="Configured decision cutoff (e.g., '11:00 Europe/London')")
    totalForecastEnergyGwh: float = Field(..., description="Total forecast wind generation energy over the period in GWh")
    totalActualEnergyGwh: float = Field(..., description="Total actual wind generation energy delivered in GWh")
    maeMw: float = Field(..., description="Mean Absolute Error in MW")
    rmseMw: float = Field(..., description="Root Mean Squared Error in MW")
    meanBiasMw: float = Field(..., description="Mean Error / Bias in MW")
    totalMatchedObservations: int = Field(..., description="Number of matched intervals")
    totalShortfallEnergyGwh: float = Field(..., description="Potential wind generation shortfall energy in GWh")
    maxShortfallMw: float = Field(..., description="Peak wind shortfall in MW")
    overforecastRatePct: float = Field(..., description="Overforecast percentage")
    underforecastRatePct: float = Field(..., description="Underforecast percentage")
    dataFreshness: str = Field(..., description="Data freshness indicator: 'LIVE', 'HISTORICAL', or 'CACHED'")
    dataSource: str = Field(..., description="Data source description (Elexon BMRS API)")
    isDemoData: bool = Field(False, description="Flag indicating whether fallback illustrative demo data is used")
    lastRefreshUtc: str = Field(..., description="Timestamp of last successful data retrieval")
